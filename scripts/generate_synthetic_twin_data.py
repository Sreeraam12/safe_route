def generate_all():
    random.seed(42)

    # 1. 01_personal_users.csv
    users_file = os.path.join(DATASET_DIR, "01_personal_users.csv")
    with open(users_file, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["user_id", "age_group", "gender", "occupation_type", "default_travel_mode", "mobility_category"])
        for arch in ARCHETYPES:
            writer.writerow([
                arch["id"],
                arch["age_group"],
                arch["gender"],
                arch["occupation_type"],
                arch["default_travel_mode"],
                arch["mobility_category"],
            ])

    # 2. 02_personal_preferences.csv
    prefs_file = os.path.join(DATASET_DIR, "02_personal_preferences.csv")
    with open(prefs_file, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow([
            "user_id",
            "lighting_preference",
            "crowd_preference",
            "isolation_aversion",
            "cctv_preference",
            "police_proximity_preference",
            "main_road_preference",
            "crime_sensitivity",
            "traffic_tolerance",
            "distance_priority",
            "time_priority",
            "detour_tolerance",
            "night_safety_weight",
            "weather_sensitivity",
        ])
        for arch in ARCHETYPES:
            p = arch["prefs"]
            writer.writerow([
                arch["id"],
                p["lighting_preference"],
                p["crowd_preference"],
                p["isolation_aversion"],
                p["cctv_preference"],
                p["police_proximity_preference"],
                p["main_road_preference"],
                p["crime_sensitivity"],
                p["traffic_tolerance"],
                p["distance_priority"],
                p["time_priority"],
                p["detour_tolerance"],
                p["night_safety_weight"],
                p["weather_sensitivity"],
            ])

    # 3. 03_personal_trips.csv, 04_route_interactions.csv, 05_personal_feedback.csv
    trips_file = os.path.join(DATASET_DIR, "03_personal_trips.csv")
    interactions_file = os.path.join(DATASET_DIR, "04_route_interactions.csv")
    feedback_file = os.path.join(DATASET_DIR, "05_personal_feedback.csv")

    trips_rows = []
    interactions_rows = []
    feedback_rows = []

    base_time = datetime(2026, 9, 1, 8, 30)

    for arch in ARCHETYPES:
        user_id = arch["id"]
        # Generate 6 trips per user
        for i in range(6):
            trip_id = f"trip_{user_id}_{i+1}"
            corridor = CHENNAI_CORRIDORS[i % len(CHENNAI_CORRIDORS)]
            trip_dt = base_time + timedelta(days=i*3, hours=random.choice([0, 4, 11, 14]))
            is_night = trip_dt.hour < 6 or trip_dt.hour >= 18

            distance_km = round(random.uniform(4.5, 12.0), 2)
            duration_min = round(distance_km * 2.8, 1)
            safety_score = round(random.uniform(72.0, 89.0), 1)

            trips_rows.append([
                trip_id,
                user_id,
                trip_dt.isoformat(),
                trip_dt.strftime("%Y-%m-%d"),
                trip_dt.strftime("%H:%M"),
                corridor[0],
                corridor[1],
                "driving",
                "Commute" if i % 2 == 0 else "Personal",
                0,
                distance_km,
                duration_min,
                safety_score,
                distance_km,
                duration_min,
                0.0,
                "Clear" if not is_night else "Dry Night",
                "Moderate",
                True,
            ])

            # 3 candidate routes per trip
            for r_idx in range(3):
                interact_id = f"int_{trip_id}_{r_idx}"
                r_dist = round(distance_km + (r_idx * 0.8), 2)
                r_dur = round(duration_min + (r_idx * 2.2), 1)
                r_risk = round(32.0 + (r_idx * 5.0), 1)
                r_safety = round(100.0 - r_risk, 1)
                is_selected = (r_idx == 0)

                interactions_rows.append([
                    interact_id,
                    trip_id,
                    user_id,
                    r_idx,
                    r_idx + 1,
                    r_dist,
                    r_dur,
                    r_risk,
                    r_safety,
                    round(random.uniform(0.6, 0.9), 2),
                    round(random.uniform(0.5, 0.85), 2),
                    round(random.uniform(0.1, 0.4), 2),
                    round(random.uniform(15.0, 35.0), 1),
                    round(random.uniform(10.0, 25.0), 1),
                    True,
                    is_selected,
                    not is_selected,
                    "" if is_selected else "Selected higher safety candidate",
                ])

            # Post-trip feedback
            fb_id = f"fb_{trip_id}"
            safety_rating = random.choice([4, 5]) if arch["id"] != "usr_arch_time_02" else random.choice([3, 4])
            feedback_rows.append([
                fb_id,
                trip_id,
                user_id,
                safety_rating,
                4,
                4 if not is_night else 5,
                4,
                5,
                False,
                "",
                False,
                "Route felt well lit and comfortable across Chennai corridor.",
                (trip_dt + timedelta(minutes=45)).isoformat(),
            ])

    with open(trips_file, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow([
            "trip_id", "user_id", "trip_datetime", "travel_date", "travel_time",
            "source_zone", "destination_zone", "travel_mode", "trip_intent",
            "selected_route_id", "selected_distance_km", "selected_duration_min",
            "selected_safety_score", "actual_distance_km", "actual_duration_min",
            "route_deviation_pct", "weather_condition", "traffic_condition", "completed"
        ])
        writer.writerows(trips_rows)

    with open(interactions_file, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow([
            "id", "trip_id", "user_id", "route_id", "route_rank", "route_distance_km",
            "route_duration_min", "route_risk", "route_safety_score", "lighting_score",
            "crowd_score", "isolation_score", "crime_risk", "traffic_risk", "viewed",
            "selected", "rejected", "rejection_reason"
        ])
        writer.writerows(interactions_rows)

    with open(feedback_file, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow([
            "id", "trip_id", "user_id", "safety_rating", "comfort_rating",
            "lighting_rating", "crowd_rating", "navigation_rating",
            "incident_reported", "incident_type", "felt_unsafe",
            "feedback_text", "created_at"
        ])
        writer.writerows(feedback_rows)

    # 4. 06_personal_segment_memory.csv
    seg_file = os.path.join(DATASET_DIR, "06_personal_segment_memory.csv")
    with open(seg_file, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow([
            "id", "user_id", "osm_segment_id", "visit_count", "selection_count",
            "rejection_count", "positive_feedback_count", "negative_feedback_count",
            "avoidance_score", "trust_score", "personal_risk_adjustment",
            "last_visit", "confidence"
        ])
        sample_segments = [2451001, 2451002, 3819001, 5928100, 7182910]
        for arch in ARCHETYPES:
            for seg in sample_segments:
                writer.writerow([
                    f"mem_{arch['id']}_{seg}",
                    arch["id"],
                    seg,
                    random.randint(3, 12),
                    random.randint(3, 10),
                    random.randint(0, 2),
                    random.randint(2, 8),
                    0,
                    0.05,
                    0.85,
                    -3.2,
                    "2026-09-20T19:00:00",
                    0.80,
                ])

    # 5. 07_personal_twin_state.csv
    twin_file = os.path.join(DATASET_DIR, "07_personal_twin_state.csv")
    with open(twin_file, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow([
            "user_id", "timestamp", "lighting_weight", "crime_weight",
            "isolation_weight", "crowd_weight", "traffic_weight",
            "distance_weight", "time_weight", "night_weight",
            "weather_weight", "detour_tolerance", "model_confidence"
        ])
        for arch in ARCHETYPES:
            p = arch["prefs"]
            writer.writerow([
                arch["id"],
                datetime.now().isoformat(),
                round(p["lighting_preference"] * 1.02, 2),
                round(p["crime_sensitivity"] * 1.01, 2),
                round(p["isolation_aversion"] * 1.01, 2),
                round(p["crowd_preference"], 2),
                round(p["traffic_tolerance"], 2),
                round(p["distance_priority"], 2),
                round(p["time_priority"], 2),
                round(p["night_safety_weight"] * 1.03, 2),
                round(p["weather_sensitivity"], 2),
                round(p["detour_tolerance"], 2),
                0.78,  # Calibrated model confidence after 6 trips
            ])

    # 6. README.md
    readme_file = os.path.join(DATASET_DIR, "README.md")
    with open(readme_file, "w", encoding="utf-8") as f:
        f.write("""# SafeRoute Personal Digital Twin Dataset (Chennai City)

> **IMPORTANT NOTICE: SYNTHETIC DEVELOPMENT DATA**  
> All files in this directory are synthetic development datasets generated specifically for testing, architecture validation, and research ablation studies within the Chennai metropolitan area. They do NOT contain real personal identifiers, Aadhaar numbers, private messages, or uncurated private trip tracking data.

## Archetypes Included
1. **Safety First** (`usr_arch_safety_01`): Prioritizes well-lit, low-isolation, highly populated corridors; high detour tolerance.
2. **Time Sensitive** (`usr_arch_time_02`): Prioritizes directness and minimal travel time with lower detour tolerance.
3. **Balanced** (`usr_arch_balanced_03`): Equitable trade-off between detour penalty and safety factors.
4. **Night Sensitive** (`usr_arch_night_04`): Stringent nighttime avoidance penalties on dark or isolated roads.
5. **Weather Sensitive** (`usr_arch_weather_05`): High aversion to poorly drained, low-visibility, or flood-prone corridors.

## File Manifest
- `01_personal_users.csv`: Coarse profile archetypes.
- `02_personal_preferences.csv`: Initial baseline preferences (normalized 0.0 - 1.0).
- `03_personal_trips.csv`: Historical trip records between major Chennai zones.
- `04_route_interactions.csv`: Candidate route impressions, choices, and rejection rationales.
- `05_personal_feedback.csv`: Post-trip subjective ratings and feedback signals.
- `06_personal_segment_memory.csv`: Road-segment-level familiarity and trust memory.
- `07_personal_twin_state.csv`: Calibrated dynamic twin weights and model confidence values.
""")

    print(f"Successfully generated all 7 Personal Twin datasets in: {DATASET_DIR}")


if __name__ == "__main__":
    generate_all()

